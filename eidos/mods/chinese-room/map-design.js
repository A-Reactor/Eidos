ChineseRoom.mapDesignGuide = `先设计空间，再填写地形。文字是像素素材的替代，不是把地点名排列成菜单。
1. 明确这个地点是做什么的：店铺、住宅、广场、河岸、树林各有不同形状和使用动线。先确定入口、可见地标、主要活动区、出口，再连接道路。
2. 以角色一格为尺度。主路尽量两格宽，交谈对象前留出停步空间；不要把 NPC 排成横排或放进只剩一个格子的死角。
3. 一个画面有一个容易辨认的中心：井、树、柜台、桥或广场。让视线和行走路径自然到达它，支路通向确实有内容的对象。
4. 草地、泥土和室内地板作为留白底色；树、墙、家具和水域成片构成形状，不把每一格都填成醒目的字。装饰沿有意义的地形聚集，留出走路的空间。
5. 自然地形有转折和疏密变化，人工建筑有清楚的轮廓与门；根据现有描述表达地貌，不凭空改变世界设定。房屋不全是空盒，野外不全是矩形围墙。
6. 出口放在相应边缘、街口或建筑门上，连接真实目的地。北侧道路与南侧道路在位置上有区分；返回同一地点时保持门和地标位置稳定。
7. 人物站在有理由的位置：店主靠柜台、守门人靠门、园丁在花圃边。使用人物名字中可辨认的单字；每个图标仍绑定真实人物 ID。
8. 由地面、阻挡地形、交互实体分层表达空间。装饰不参与物品奖励；可互动对象引用现有 NPC、线索、动作和出口，不新建一套任务或背包。
9. 先检查入口可达、道路连续、没有孤岛，且人物和出口能走到相邻格。对主角当前位置作同样检查。不要靠任意传送补救坏地图。
10. 玩家探索、对话、调查后才触发真实事件。走格子不是消耗行动次数的回合；普通阻挡只停止移动，面向人物按确认键交互。
11. 小房间一屏可读；城镇、河岸等可比一屏更大，镜头随主角移动。不要通过缩小所有字来容纳大地图，避免空旷的超大场景。
12. 回访与更新保留已确认结构，按新的公开剧情调整物件与局部环境。最终自查：能否一眼看懂道路、主要地标、人物位置和离开的方向？`;
