import { expect, it, vi } from 'vitest';
import { watchSpeculativeVoice } from '@/lib/game/momoi/speculative-prefetch';
import { SpeculativeEngine, type SpeculationInput } from '@/lib/ai/speculation';
import { VoiceLibrary } from '@/lib/game/momoi/library';
import { buildVoiceRequest, DEFAULT_VOICE_CONFIG } from '@/lib/game/momoi/model';
import { buildRiftCityStartState } from '@/lib/test/fixtures';
import type { AIGameResponse } from '@/lib/ai/types';
const { world, snapshot } = buildRiftCityStartState();
const input: SpeculationInput = { scope: 'voice-parent', world, snapshot, recentHistory: [], inventory: [], clues: [], encyclopedia: [], criticalFacts: [], questLog: [], weather: '晴', protagonistState: null, clientSettings: null };
const response = { validity: { isPossible: true }, segments: [{ type: 'dialogue', text: '候选第一句。', speaker: '甲' }, { type: 'dialogue', text: '候选第二句。', speaker: '乙' }] } as AIGameResponse;
const audio = { audioBase64: 'UklGRg==', mimeType: 'audio/wav' };
it('warms just the primary first line behind foreground work, then shares it with selected playback', async () => {
  let release!: (value: typeof audio) => void;
  const calls: string[] = [];
  const library = new VoiceLibrary({}, async () => {}, async request => { calls.push(request.text); return calls.length === 1 ? new Promise(resolve => { release = resolve; }) : audio; });
  const current = library.ensure(buildVoiceRequest({ type: 'dialogue', text: '当前。' }, DEFAULT_VOICE_CONFIG)!, false, { priority: 'current' });
  await vi.waitFor(() => expect(calls).toEqual(['当前。']));
  const finishes: ((value: AIGameResponse) => void)[] = [];
  const engine = new SpeculativeEngine(2, undefined, () => new Promise(resolve => finishes.push(resolve)));
  const watch = watchSpeculativeVoice({ engine, library, scope: () => input.scope, ready: () => true, requestForSegment: segment => buildVoiceRequest(segment, DEFAULT_VOICE_CONFIG) });
  const work = engine.triggerSpeculation(['首选', '备选'], input);
  finishes[1](response); await Promise.resolve(); expect(library.queueItems).toHaveLength(1);
  finishes[0](response); await work;
  await vi.waitFor(() => expect(library.queueItems).toHaveLength(2));
  expect(library.queueItems[1]).toMatchObject({ text: '候选第一句。', priority: 'speculative' });
  release(audio); await current;
  await vi.waitFor(() => expect(Object.keys(library.assets)).toHaveLength(2));
  expect(engine.checkCache('首选', input.scope)).toBe(response);
  await library.ensure(buildVoiceRequest(response.segments[0], DEFAULT_VOICE_CONFIG)!, false, { priority: 'current' });
  expect(calls).toEqual(['当前。', '候选第一句。']); watch.dispose(); library.dispose();
});
it('removes stale waiting predictions and does not pay for translated or external speculative voices', async () => {
  let release!: (value: typeof audio) => void;
  const synthesize = vi.fn(() => new Promise<typeof audio>(resolve => { release = resolve; }));
  const library = new VoiceLibrary({}, async () => {}, synthesize);
  const current = library.ensure(buildVoiceRequest({ type: 'dialogue', text: '当前。' }, DEFAULT_VOICE_CONFIG)!);
  await vi.waitFor(() => expect(synthesize).toHaveBeenCalledOnce());
  const engine = new SpeculativeEngine(1, undefined, async () => response);
  let mode: 'original' | 'japanese' = 'original';
  let provider: 'legacy' | 'compatible' = 'legacy';
  const watch = watchSpeculativeVoice({ engine, library, scope: () => input.scope, ready: () => true,
    requestForSegment: segment => buildVoiceRequest(segment, { ...DEFAULT_VOICE_CONFIG, provider, material: mode }) });
  await engine.triggerSpeculation(['首选'], input);
  await vi.waitFor(() => expect(library.queueItems).toHaveLength(2));
  engine.cancel(); expect(library.queueItems).toHaveLength(1);
  mode = 'japanese'; await engine.triggerSpeculation(['首选'], input);
  await Promise.resolve(); expect(library.queueItems).toHaveLength(1);
  mode = 'original'; provider = 'compatible'; watch.sync();
  await Promise.resolve(); expect(library.queueItems).toHaveLength(1);
  expect(synthesize).toHaveBeenCalledOnce(); watch.dispose(); release(audio); await current; library.dispose();
});
