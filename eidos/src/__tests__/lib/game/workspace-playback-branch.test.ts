// @vitest-environment jsdom
import 'fake-indexeddb/auto';
import { expect, it } from 'vitest';
import { useGameStore } from '@/store/game-store';
import { buildRiftCityStartState } from '@/lib/test/fixtures';
import { currentDocumentScope } from '@/lib/game/model-documents';
import { saveLocalDocument } from '@/lib/game/documents/ingest';
import { loadDocuments, readDocument } from '@/lib/game/documents/repository';
import { createWorkspaceSession, runWorkspaceTool } from '@/lib/game/workspace/session';
import { prepareActionArtifacts, finalizeActionArtifacts } from '@/lib/game/documents/action-artifacts';
import { mergeWorkspaceBranchAt } from '@/lib/game/workspace/branch';

it('keeps files on a private branch until their paragraph plays, merges once, and rewinds versions', async () => {
  const { world } = buildRiftCityStartState();
  useGameStore.setState({ ...useGameStore.getInitialState(), currentWorld: world, currentPlaythroughId: crypto.randomUUID(), sandboxMode: true, sandboxDossierId: '002' });
  const state = useGameStore.getState(); await state.initWorldLine(state.currentPlaythroughId!, world.id);
  const scope = currentDocumentScope(useGameStore.getState())!;
  const old = await saveLocalDocument(scope, { title: '旧稿', content: '原文', format: 'text' });
  const rootState = useGameStore.getState();
  const { hashAndStore } = await import('@/lib/game/cas-storage');
  const root = { ...rootState.currentNode!, snapshotHash: await hashAndStore('snapshot', rootState.createSnapshot()) };
  useGameStore.setState({ currentNode: root, allNodes: { [root.id]: root } });
  const parent = root.id;
  const session = await createWorkspaceSession({ scope, actionId: 'branch', parentNodeId: parent, inputs: [], library: [old], writableDocuments: [old] });
  const receipt = await runWorkspaceTool(session, { method: 'files.write', params: { path: `library/${old.documentId}/source.txt`, text: '修改后的正文', expectedVersion: old.revision } });
  const segments = [{ type: 'narration' as const, text: '她打开书桌。' }, { type: 'narration' as const, text: '她完成了改稿。', workspaceEffects: [receipt.operationId!] }];
  const prepared = await prepareActionArtifacts({ scope, actionId: 'branch', session, inputs: [], segments, effectIds: [receipt.operationId!], documents: [{ key: 'new', title: '新报告', format: 'text', content: '完整新报告', segmentIndex: 1 }] });
  const node = await useGameStore.getState().addActionNode({ id: 'branch', summary: '修改旧稿', worldImpacts: [], availableActions: [], sceneId: state.currentSceneId, sceneName: '', timestamp: Date.now(), playerInput: '修改旧稿', aiResponse: segments.map(s => s.text).join('\n\n'), gameTime: state.gameTime, timeSpent: { day: 0, hour: 0, minute: 0 }, workspaceBranch: prepared.branch, outputDocuments: prepared.outputDocuments } as never, useGameStore.getState().createSnapshot(), segments);
  await finalizeActionArtifacts(prepared, node);
  expect((await loadDocuments(scope)).map(d => d.currentRevision)).toEqual([old.revision]);
  await mergeWorkspaceBranchAt(useGameStore, node.id, 0);
  expect((await loadDocuments(scope)).map(d => d.currentRevision)).toEqual([old.revision]);
  useGameStore.getState().setNodeReadText(node.id, segments[0].text);
  const { createActionWorkspace } = await import('@/lib/game/workspace/action-session');
  const { createStreamRequestScope } = await import('@/lib/game/stream-lifecycle');
  const continuing = await createActionWorkspace(useGameStore.getState(), [], createStreamRequestScope(useGameStore.getState()), () => true);
  expect(Object.values(continuing!.documentByPath).some(ref => ref.documentId === prepared.outputDocuments[0].documentId)).toBe(false);
  const concurrent = await saveLocalDocument(scope, { title: '旧稿', content: '玩家并发修改', format: 'text', previous: old });
  await expect(mergeWorkspaceBranchAt(useGameStore, node.id, 1)).rejects.toThrow('冲突');
  expect(await loadDocuments(scope)).toHaveLength(1);
  expect((await loadDocuments(scope))[0].currentRevision).toBe(concurrent.revision);
  await saveLocalDocument(scope, { title: '旧稿', content: '原文', format: 'text', previous: concurrent });
  const portable = await useGameStore.getState().exportWorldLine(node.id);
  expect(portable.documents?.records).toHaveLength(2);
  expect(portable.documents?.records.some(doc => doc.staged)).toBe(true);
  const { importWorldLineExport } = await import('@/lib/game/worldline-export');
  const destId = crypto.randomUUID();
  const imported = await importWorldLineExport(portable, world.id, destId, { sandboxMode: true, sandboxDossierId: '002' });
  expect(imported.allNodes[node.id].workspaceBranch?.scope.playthroughId).toBe(destId);
  await mergeWorkspaceBranchAt(useGameStore, node.id, 1);
  expect((await readDocument(scope, { documentId: old.documentId, revision: receipt.afterVersion! })).resource.text).toBe('修改后的正文');
  expect((await loadDocuments(scope)).find(d => d.id === old.documentId)?.currentRevision).toBe(receipt.afterVersion);
  expect(await loadDocuments(scope)).toHaveLength(2);
  await mergeWorkspaceBranchAt(useGameStore, node.id, 1);
  expect(await loadDocuments(scope)).toHaveLength(2);
  await useGameStore.getState().backtrackToNode(parent);
  expect((await loadDocuments(scope)).map(d => d.currentRevision)).toEqual([old.revision]);
  const { loadBlob } = await import('@/lib/game/cas-storage');
  useGameStore.getState().restoreSnapshot((await loadBlob(imported.allNodes[node.id].snapshotHash)) as never);
  useGameStore.setState({ currentPlaythroughId: destId, worldLine: imported.meta, allNodes: imported.allNodes, currentNode: imported.allNodes[node.id] });
  await mergeWorkspaceBranchAt(useGameStore, node.id, 1);
  expect(await loadDocuments({ ...scope, playthroughId: destId })).toHaveLength(2);
});
