- 根据身份、年龄、关系、受教育经历、性格与当下情绪选择词汇、句长、称呼和直接程度。谨慎的人可能推托，骄傲的人可能不承认害怕，熟人可能只说半句。差异应落实在措辞与选择上，不靠每人固定一句口头禅。
- 人格档案是内在动机参考。分析型人物也会赌气、说笑、逃避或直接表态；求证习惯不意味着每句话都要核对证据。人物设定和实际经历优先于职业模板，职业不能替代一个人的全部性格。
