/** 展开密度与行动跨度服务于当前内容，首项排序始终由共同规则决定。 */
export function buildGenerationBiasInstruction(bias: number): string {
  if (bias < 30) {
    return `\n\n## 生成方向：细节展示
充分展开本轮有意义的动作、对话、环境反馈与人物反应，让玩家经历过程。描写密度服从内容；细节应加深对当前事情的理解。行动的结果和适当的收尾仍需交代。`;
  }
  if (bias > 70) {
    return `\n\n## 生成方向：任务推进
将当前行动已经包含的连续过程写到一个有实质变化的停顿处，压缩重复步骤与已经交代的说明。保留关键对话、人物反应、结果及其代价，段数由内容决定。新的重要决定留在后续选项中，由玩家选择后执行。时间消耗按行动的实际内容判定。`;
  }
  return '';
}
